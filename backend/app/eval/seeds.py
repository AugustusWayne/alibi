"""Reading the frozen seed list.

`eval/seeds.json` is frozen before any seed in it is generated (spec 8.4.3).
This module only reads it. Nothing in the repo writes it, and regenerating it
after a result is known voids every number already recorded — which is a thing
to write down in `PROGRESS.md`, not a thing to do quietly.

The file's `_`-prefixed keys carry the freeze date and the rule the list was
generated by, so the list can be re-derived and checked by anyone.
"""

from __future__ import annotations

import json
from pathlib import Path

DEFAULT_PATH = Path("eval/seeds.json")

DEVELOPMENT_SEED = 7777
"""Inspected at length during M1 and M2, so it is not a blind seed.

It stays out of the eval set and in `test_provenance.py`, where the
seed-7777 ground-truth comparison is the pattern this harness generalises.
"""

TEST_SEED_FLOOR = 900_000
"""`backend/tests/conftest.py` hands these out on the shared server."""


def load_seeds(path: str | Path = DEFAULT_PATH) -> list[int]:
    """The frozen seeds, in file order, checked for the two exclusions.

    Raises rather than filtering. A seed that should not be in the set is a
    broken freeze, and silently dropping it would change the denominator of
    every published figure without saying so.
    """
    doc = json.loads(Path(path).read_text())
    seeds = [int(s) for s in doc["seeds"]]

    if len(seeds) != len(set(seeds)):
        duplicates = sorted({s for s in seeds if seeds.count(s) > 1})
        raise ValueError(f"{path}: duplicate seeds {duplicates}")
    if DEVELOPMENT_SEED in seeds:
        raise ValueError(
            f"{path}: the development seed {DEVELOPMENT_SEED} has been inspected and "
            f"cannot be part of a blind evaluation set (spec 8.4.3)"
        )
    too_high = [s for s in seeds if s >= TEST_SEED_FLOOR]
    if too_high:
        raise ValueError(
            f"{path}: seeds {too_high} collide with the range conftest hands out to "
            f"tests on the shared server"
        )
    return seeds
